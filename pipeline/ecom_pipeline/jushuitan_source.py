def normalize_jushuitan_columns(frame: pl.DataFrame) -> pl.DataFrame:
    renames = {source: target for source, target in HEADER_ALIASES.items() if source in frame.columns}
    collisions = sorted(target for target in renames.values() if target in frame.columns)
    if collisions:
        raise ValueError(f"聚水潭源文件同时包含原列名与注释列名: {', '.join(collisions)}")
    return frame.rename(renames) if renames else frame

